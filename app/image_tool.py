"""Workout card image generation tool for FitCoach AI using PIL and GCS."""

import io
import uuid
from google.cloud import storage
from PIL import Image, ImageDraw, ImageFont

PROJECT_ID = "qwiklabs-gcp-02-210a21fedfc2"
BUCKET_NAME = "fitcoach-ai-media-qwiklabs-gcp-02-210a21fedfc2"


def generate_workout_card_image(title: str, details: str) -> str:
    """Generate a custom visual workout infographic card PNG and return its public URL.

    Args:
        title: Title of the workout or routine (e.g. 'Chest & Triceps Power Session').
        details: Bullet points or breakdown of exercises, sets, and reps.

    Returns:
        Public image URL of the generated workout card.
    """
    try:
        width, height = 800, 500
        # Dark modern theme background
        bg_color = (20, 24, 33)
        accent_color = (0, 220, 130)  # Neon green accent
        text_color = (240, 240, 245)
        sub_text_color = (180, 185, 200)
        card_bg = (32, 38, 52)

        img = Image.new("RGB", (width, height), color=bg_color)
        draw = ImageDraw.Draw(img)

        # Header banner card
        draw.rounded_rectangle([30, 30, width - 30, 110], radius=12, fill=card_bg)
        draw.rectangle([30, 30, 42, 110], fill=accent_color)  # Left accent bar

        # Draw Title
        draw.text((60, 48), "FITCOACH AI | WORKOUT CARD", fill=accent_color)
        draw.text((60, 68), title.upper()[:45], fill=text_color)

        # Content Card
        draw.rounded_rectangle([30, 130, width - 30, height - 40], radius=12, fill=card_bg)

        # Draw Details Lines
        lines = [line.strip() for line in details.split("\n") if line.strip()][:10]
        y_pos = 160
        for line in lines:
            if line.startswith("-") or line.startswith("*"):
                draw.ellipse([50, y_pos + 4, 58, y_pos + 12], fill=accent_color)
                draw.text((70, y_pos), line.lstrip("-* ").strip()[:65], fill=text_color)
            else:
                draw.text((50, y_pos), line[:70], fill=sub_text_color)
            y_pos += 30

        # Footer badge
        draw.text((width - 250, height - 30), "Generated by FitCoach AI", fill=sub_text_color)

        # Save image to byte buffer
        buffer = io.BytesIO()
        img.save(buffer, format="PNG")
        image_bytes = buffer.getvalue()

        # Upload to GCS
        filename = f"workout_card_{uuid.uuid4().hex[:8]}.png"
        storage_client = storage.Client(project=PROJECT_ID)
        bucket = storage_client.bucket(BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(image_bytes, content_type="image/png")

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"
        return f"Successfully generated workout card image! Public URL: {public_url}"

    except Exception as e:
        return f"Error generating workout card image: {e}"
